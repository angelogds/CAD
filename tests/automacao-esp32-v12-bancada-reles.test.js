 assert.match(firmware,/#define CGD_ENABLE_PURGE_OUTPUTS 1/);
 assert.match(firmware,/#define CGD_ENABLE_MATERIAL_GATE_OUTPUTS 1/);
 assert.match(firmware,/void apply\(bool allow,bool loadOpen,bool dischargeOpen\)/);
 assert.match(firmware,/\(loadOpen&&dischargeOpen\)/);
 assert.match(firmware,/#define CGD_GATE_FEED_OPEN_GPIO 32/);
 assert.match(firmware,/#define CGD_GATE_DISCHARGE_OPEN_GPIO 33/);
